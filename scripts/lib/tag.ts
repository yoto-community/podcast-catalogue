/** Tags connus (`reference/tags.json`) — garantit que la proposition reste dans l'enum. */
const knownTags = new Set<string>(loadTags().map((t) => t.id));

/** Tags retenus dans le texte, dans l'ordre canonique de `TAG_KEYWORDS`. */
export function matchTags(text: string): string[] {
  const normalized = normalizeName(text);
  const words = normalized.split(" ");
  const matched: string[] = [];
  for (const [tagId, keywords] of Object.entries(TAG_KEYWORDS)) {
    if (
      keywords.some((kw) => {
        const needle = normalizeName(kw);
        if (!needle) return false;
        // Mot-clé très court (« ia », « roi », « art », « mer ») : mot entier exigé,
        // sinon « mer » matcherait « merveilleuses » et « ia »… « daily ».
        return needle.length <= 3 ? words.includes(needle) : normalized.includes(needle);
      })
    ) {
      matched.push(tagId);
    }
  }
  return [...new Set(matched)];
}

/**
 * Tags proposés pour une entrée : mot-clés sur `nom + description + catégorie`,
 * repli sur la catégorie si elle a un équivalent, plafonné à `LIMITS.tags`.
 */
export function suggestTags(
  entry: Pick<SourceEntry, "name" | "category"> & { description?: string },
): SourceTag[] {
  const matched = matchTags(`${entry.name} ${entry.description ?? ""} ${entry.category}`).filter(
    (t) => knownTags.has(t),
  );
  const fallback = knownTags.has(entry.category) ? [entry.category] : [];
  const tags = (matched.length > 0 ? matched : fallback).slice(0, LIMITS.tags);
  // `knownTags` est construit depuis reference/tags.json, qui EST l'enum `SourceTag`.
  return tags as SourceTag[];
}
